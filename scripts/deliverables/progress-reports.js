function report(s) {
  const logs = LOGS.filter((l) => l.no >= s.logs[0] && l.no <= s.logs[1]);
  const range = `log/${String(s.logs[0]).padStart(3, '0')} ~ log/${String(s.logs[1]).padStart(3, '0')}`;
  const decisionRows = s.decisions.map((id) => {
    if (!DECISIONS.has(id)) throw new Error(`결정 인덱스에 없음: ${id}`);
    return [id, DECISIONS.get(id)];
  });
  const children = [
    ...cover(`단계별 개발 진행 보고서 ${s.no}/5`, s.name, [
      ['단계', `${s.no}부 — ${s.name}`],
      ['기간', s.period],
      ['근거 기록', `진행 기록 ${range}(${logs.length}건)`],
      ['작성일', TODAY],
      ['원천', '저장소 docs/log(진행 기록)·docs/decisions(결정 기록) — scripts/deliverables/progress-reports.js로 생성'],
    ], { toc: false }),
    h2('1. 단계 목표'),
    p(s.goal),
    ...(s.before ? [callout('이 단계 이전', [s.before])] : []),
    h2('2. 주요 결과'),
    ...bullets(s.results),
    h2('3. 이 단계의 결정'),
    p('결정 하나에 기록 하나(저장소 decisions 폴더의 D 번호 파일). 아래는 결정 인덱스의 요약을 그대로 옮긴 것이다 — 지금 상태는 인덱스에서 본다.'),
    table(['ID', '결정'], decisionRows, [1, 7]),
    h2('4. 검증'),
    ...bullets(s.verify),
    h2('5. 문제와 대응'),
    table(['문제', '대응', '근거'], s.issues, [4, 4, 1.4]),
    h2('6. 다음 단계로 넘긴 것'),
    ...bullets(s.next),
    h2(`부록. 작업 기록 (${range})`),
    p('각 기록은 계기 → 한 일 → 근거·수치 → 검증 순서로 저장소 log 폴더의 번호 파일에 있다.'),
    table(['번호', '날짜', '제목'], logs.map((l) => [String(l.no).padStart(3, '0'), l.date, l.title]), [0.8, 1.4, 7]),
  ];
  return build(path.join(OUT_DIR, `진행보고서_${s.no}_${s.key}.docx`), `단계별 개발 진행 보고서 ${s.no}/5`, children);
}

// 구간이 빠짐없이 이어지는지 — 다음 기록이 생기면 마지막 단계 끝 번호를 늘린다.
STAGES.forEach((s, i) => {
  if (i > 0 && s.logs[0] !== STAGES[i - 1].logs[1] + 1) throw new Error(`${s.no}부 시작이 앞 단계와 이어지지 않음`);
});
Promise.all(STAGES.map(report)).catch((e) => { console.error(e); process.exit(1); });
